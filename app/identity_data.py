def parse_discover(answers: Any) -> list[int]:
    if not isinstance(answers, list) or len(answers) != DISCOVER_COUNT:
        raise IdentityInputError(f"ต้องตอบให้ครบ {DISCOVER_COUNT} ข้อ")
    picked: list[int] = []
    for index, value in enumerate(answers):
        if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value < len(DISCOVER_QUESTIONS[index]["choices"]):
            raise IdentityInputError(f"คำตอบข้อ {index + 1} ไม่ถูกต้อง")
        picked.append(value)
    return picked


def _discover_scores(picked: list[int]) -> dict[str, int]:
    earned = {key: 0 for key in TRAITS}
    available = {key: 0 for key in TRAITS}
    for question, index in zip(DISCOVER_QUESTIONS, picked):
        for key, value in question["choices"][index]["traits"].items():
            earned[key] += value
        for key in TRAITS:
            available[key] += max(choice["traits"].get(key, 0) for choice in question["choices"])
    return {key: round(100 * earned[key] / available[key]) for key in TRAITS if available[key] > 0}


# ---------- จับคู่โปรไฟล์กับอาชีพ ----------
def _align(profile: dict[str, float], career: dict[str, Any]) -> int:
    """ความสอดคล้องระหว่างโปรไฟล์สไตล์กับสิ่งที่อาชีพใช้ (0-100, 50 = เป็นกลาง)

    ใช้สหสัมพันธ์ (cosine ของเวกเตอร์ที่หักค่าเฉลี่ยแล้ว) เพื่อไม่ให้ผลเพี้ยนเมื่อโปรไฟล์มาจากแบบบังคับเลือก
    ซึ่งคะแนนทุกมิติรวมกันเป็นค่าคงที่ — สนใจ \"ลำดับว่ามิติไหนเด่นกว่า\" มากกว่าตัวเลขสัมบูรณ์
    """
    keys = [key for key in TRAITS if key in profile]
    if len(keys) < 2:
        return 50
    p_mean = sum(profile[key] for key in keys) / len(keys)
    w_mean = sum(career["weights"][key] for key in keys) / len(keys)
    p = [profile[key] - p_mean for key in keys]
    w = [career["weights"][key] - w_mean for key in keys]
    norm = (sum(x * x for x in p) ** 0.5) * (sum(x * x for x in w) ** 0.5)
    if norm == 0:
        return 50
    cosine = sum(a * b for a, b in zip(p, w)) / norm
    return round(50 + 50 * max(-1.0, min(1.0, cosine)))


def rank_careers(profile: dict[str, float], actual: dict[str, int] | None = None) -> list[dict[str, Any]]:
    """จัดอันดับทุกอาชีพ — อาชีพที่เคยลองแล้วถ่วงผลจริง 60% + โปรไฟล์ 40%, ที่ยังไม่เคยลองใช้โปรไฟล์ล้วน"""
    actual = actual or {}
    top_traits = sorted(profile, key=lambda key: (-profile[key], key))[:3]
    rows = []
    for career in CAREERS:
        predicted = _align(profile, career)
        tried = career["id"] in actual
        score = round(0.6 * actual[career["id"]] + 0.4 * predicted) if tried else predicted
        matched = [key for key in top_traits if career["weights"][key] >= 2]
        rows.append({
            "career_id": career["id"], "name": career["name"], "icon": career["icon"], "tone": career["tone"],
            "group": career["group"], "group_label": GROUPS[career["group"]],
            "score": score, "predicted": predicted, "tried": tried, "fit": actual.get(career["id"]),
            "matched": [TRAITS[key]["label"] for key in matched],
        })
    rows.sort(key=lambda row: (-row["score"], row["name"]))
    return rows


def _faculties_from(rows: list[dict[str, Any]], limit: int = 8) -> list[str]:
    """รวมคณะจากอาชีพอันดับต้น ๆ ถ่วงด้วยคะแนนและอันดับ (คณะที่ซ้ำหลายอาชีพได้คะแนนสูงขึ้น)"""
    totals: dict[str, float] = {}
    order: dict[str, int] = {}
    for rank, row in enumerate(rows[:5]):
        for name in CAREER_BY_ID[row["career_id"]]["faculties"]:
            totals[name] = totals.get(name, 0.0) + row["score"] * (1 - rank * 0.1)
            order.setdefault(name, len(order))
    return sorted(totals, key=lambda name: (-totals[name], order[name]))[:limit]


def evaluate_discover(answers: Any) -> dict[str, Any]:
    """สรุปผลแบบสำรวจภาพรวม — โปรไฟล์ 6 มิติ + อาชีพที่เข้ากับโปรไฟล์มากที่สุดจาก \"ทุกอาชีพ\" ในระบบ"""
    picked = parse_discover(answers)
    scores = _discover_scores(picked)
    rows = rank_careers({key: float(value) for key, value in scores.items()})
    return {
        "kind": "discover",
        "career_id": "discover",
        "career_name": "แบบสำรวจภาพรวม",
        "icon": "🧭",
        "answers": picked,
        "traits": [{"key": key, "label": TRAITS[key]["label"], "desc": TRAITS[key]["desc"], "score": scores[key]} for key in TRAITS],
        "archetype": archetype_for(scores),
        "top_careers": rows[:8],
        "faculties": _faculties_from(rows),
        "low_traits": [
            {"key": key, "label": TRAITS[key]["label"], "text": TRAIT_ADVICE[key]["grow"]}
            for key in sorted(scores, key=lambda k: (scores[k], k))[:2]
        ],
        "confidence": CONFIDENCE_NOTE,
        "disclaimer": DISCLAIMER,
    }


