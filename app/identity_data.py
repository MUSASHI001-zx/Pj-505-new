class IdentityInputError(ValueError):
    """คำตอบที่ส่งมาไม่ถูกต้อง (ข้อความเป็นภาษาไทยพร้อมแสดงให้ผู้ใช้)"""


def _validate_data() -> None:
    """ตรวจโครงสร้างข้อมูลตอนโหลดโมดูล — กันพิมพ์รหัสมิติผิดหรือจำนวนตัวเลือกไม่ครบ"""
    for career in CAREERS:
        assert set(career["weights"]) == set(TRAITS), f"{career['id']}: weights ต้องครบทุกมิติ"
        assert len(career["scenarios"]) == 5, f"{career['id']}: ต้องมี 5 สถานการณ์"
        for scenario in career["scenarios"]:
            assert len(scenario["choices"]) == 4, f"{career['id']}: ทุกสถานการณ์ต้องมี 4 ตัวเลือก"
            for choice in scenario["choices"]:
                assert choice["traits"] and set(choice["traits"]) <= set(TRAITS), f"{career['id']}: รหัสมิติไม่ถูกต้อง"
        assert career["group"] in GROUPS, f"{career['id']}: หมวดอาชีพไม่ถูกต้อง"
        assert career["try_it"] and career["related"], f"{career['id']}: ต้องมี try_it และ related"
        assert all(rid in CAREER_BY_ID and rid != career["id"] for rid in career["related"]), f"{career['id']}: related ไม่ถูกต้อง"


_validate_data()


def _style(career: dict[str, Any], picked: list[int]) -> tuple[dict[str, int], dict[str, int], float]:
    """คะแนนแต่ละมิติ (0-100), น้ำหนักของมิติที่วัดได้, และคะแนนสไตล์ดิบแบบถ่วงน้ำหนัก

    คะแนนมิติ t = คะแนนที่ได้ / คะแนนสูงสุดที่สถานการณ์ของอาชีพนี้เปิดโอกาสให้ทำได้ในมิตินั้น
    มิติที่ไม่มีสถานการณ์ใดวัดได้เลย (available = 0) ถือว่าวัดไม่ได้และไม่นำมาคิด
    """
    earned = {key: 0 for key in TRAITS}
    available = {key: 0 for key in TRAITS}
    for scenario, choice_index in zip(career["scenarios"], picked):
        for key, value in scenario["choices"][choice_index]["traits"].items():
            earned[key] += value
        for key in TRAITS:
            available[key] += max(choice["traits"].get(key, 0) for choice in scenario["choices"])
    scores = {key: round(100 * earned[key] / available[key]) for key in TRAITS if available[key] > 0}
    weights = {key: career["weights"][key] for key in scores if career["weights"][key] > 0}
    weight_sum = sum(weights.values()) or 1
    raw = sum(100 * earned[key] / available[key] * weight for key, weight in weights.items()) / weight_sum
    return scores, weights, raw


def _style_range() -> dict[str, tuple[float, float]]:
    """คะแนนสไตล์ดิบต่ำสุด/สูงสุดที่เป็นไปได้ของแต่ละอาชีพ (ไล่ครบทุกชุดคำตอบ 4^5 = 1,024 แบบ)"""
    ranges: dict[str, tuple[float, float]] = {}
    for career in CAREERS:
        values = [_style(career, list(combo))[2] for combo in itertools.product(range(4), repeat=len(career["scenarios"]))]
        ranges[career["id"]] = (min(values), max(values))
    return ranges


STYLE_RANGE = _style_range()


