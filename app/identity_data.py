def parse_answers(career: dict[str, Any], answers: Any, enjoyment: Any) -> tuple[list[int], int]:
    """ตรวจและแปลงคำตอบ — ต้องตอบครบทุกข้อ ตัวเลือก 0-3 และความชอบ 1-5"""
    total = len(career["scenarios"])
    if not isinstance(answers, list) or len(answers) != total:
        raise IdentityInputError(f"ต้องตอบให้ครบ {total} ข้อ")
    picked: list[int] = []
    for index, value in enumerate(answers):
        if isinstance(value, bool) or not isinstance(value, int):
            raise IdentityInputError(f"คำตอบข้อ {index + 1} ไม่ถูกต้อง")
        if not 0 <= value < len(career["scenarios"][index]["choices"]):
            raise IdentityInputError(f"คำตอบข้อ {index + 1} ไม่ถูกต้อง")
        picked.append(value)
    if isinstance(enjoyment, bool) or not isinstance(enjoyment, int) or not 1 <= enjoyment <= 5:
        raise IdentityInputError("กรุณาให้คะแนนความรู้สึกชอบ 1-5")
    return picked, enjoyment


def fit_label(fit: int) -> str:
    if fit >= 75:
        return "เข้ากับสไตล์ของเธอมาก"
    if fit >= 55:
        return "ค่อนข้างเข้ากัน"
    if fit >= 35:
        return "ลองสำรวจเพิ่มเติม"
    return "อาจยังไม่ใช่สไตล์ของเธอตอนนี้"


def evaluate(career_id: str, answers: Any, enjoyment: Any) -> dict[str, Any]:
    """คำนวณผลสรุปของการจำลองอาชีพหนึ่งอาชีพ (ฟังก์ชันบริสุทธิ์ ไม่แตะฐานข้อมูล)

    ความเหมาะ = 75% × สไตล์การตอบเทียบกับสิ่งที่อาชีพต้องใช้ (ปรับสเกล 0-100) + 25% × ความรู้สึกชอบ
    """
    career = CAREER_BY_ID.get(str(career_id))
    if career is None:
        raise IdentityInputError("ไม่พบอาชีพที่เลือก")
    picked, enjoy = parse_answers(career, answers, enjoyment)

    scores, weights, raw_style = _style(career, picked)
    lo, hi = STYLE_RANGE[career["id"]]
    # ปรับสเกลให้ 0 = ตอบสวนทางกับที่อาชีพต้องการที่สุด, 100 = ตอบเข้ากับอาชีพนี้ที่สุดเท่าที่ทำได้
    style_fit = 100 * (raw_style - lo) / (hi - lo) if hi > lo else 50.0
    enjoy_fit = (enjoy - 1) / 4 * 100
    fit = round(SKILL_WEIGHT * style_fit + ENJOY_WEIGHT * enjoy_fit)

    # จุดแข็ง = มิติที่อาชีพต้องใช้มาก และเธอได้คะแนนสูง / ข้อควรฝึก = ต้องใช้มากแต่คะแนนต่ำ
    needed = sorted(weights, key=lambda key: (-weights[key], key))
    strengths = [key for key in needed if weights[key] >= 2 and scores[key] >= 60][:3]
    to_grow = [key for key in needed if weights[key] >= 2 and scores[key] < 45][:2]

    ranked = sorted(scores, key=lambda key: (-scores[key], key))
    top_need = sorted(TRAITS, key=lambda key: (-career["weights"][key], key))[:2]
    top_mine = ranked[:2]
    overlap = [key for key in top_mine if key in top_need]
    mine_text = "และ".join(TRAITS[key]["label"] for key in top_mine)
    need_text = "และ".join(TRAITS[key]["label"] for key in top_need)
    if overlap:
        insight = f"ในสถานการณ์เหล่านี้เธอเลือกตอบแนว{mine_text}มากที่สุด ซึ่งตรงกับสิ่งที่{career['name']}ใช้มาก ({need_text})"
    else:
        insight = f"ในสถานการณ์เหล่านี้เธอเลือกตอบแนว{mine_text}มากที่สุด ขณะที่{career['name']}ใช้{need_text}มากที่สุด — ลองคิดดูว่าเธอสนุกกับส่วนนั้นหรือไม่"
    unused = [key for key in ranked if career["weights"][key] == 0 and scores[key] >= 70][:2]

    return {
        "kind": "career",
        "career_id": career["id"],
        "group": career["group"],
        "group_label": GROUPS[career["group"]],
        "answers": picked,
        "archetype": archetype_for(scores),
        "insight": insight,
        "unused_strengths": [
            {"key": key, "label": TRAITS[key]["label"], "text": f"เธอได้คะแนน{TRAITS[key]['label']}สูง แต่อาชีพนี้ใช้ทักษะนี้ไม่มาก — อาจเหมาะกับอาชีพอื่นที่ใช้มันเต็มที่กว่า"}
            for key in unused
        ],
        "try_it": list(career["try_it"]),
        "related": [{"id": rid, "name": CAREER_BY_ID[rid]["name"], "icon": CAREER_BY_ID[rid]["icon"]} for rid in career["related"]],
        "confidence": CONFIDENCE_NOTE,
        "career_name": career["name"],
        "icon": career["icon"],
        "fit": fit,
        "label": fit_label(fit),
        "style_fit": round(style_fit),
        "enjoyment": enjoy,
        "enjoyment_label": ENJOYMENT_LABELS[enjoy],
        "traits": [
            {"key": key, "label": TRAITS[key]["label"], "score": scores[key], "weight": career["weights"][key]}
            for key in TRAITS if key in scores
        ],
        "strengths": [{"key": key, "label": TRAITS[key]["label"], "text": TRAIT_ADVICE[key]["strong"]} for key in strengths],
        "to_grow": [{"key": key, "label": TRAITS[key]["label"], "text": TRAIT_ADVICE[key]["grow"]} for key in to_grow],
        "faculties": list(career["faculties"]),
        "reality": career["reality"],
        "disclaimer": DISCLAIMER,
    }


